    expect(AITABLE_RECORD_QUERY_DEFAULT).toBe(20);
    expect(AITABLE_RECORDS_MAX).toBe(20);
    expect(AITABLE_FIELDS_MAX).toBe(50);
    expect(AITABLE_CELL_MAX).toBe(2000);
    expect(AITABLE_RECORD_QUERY_TEXT_MAX).toBe(200);
